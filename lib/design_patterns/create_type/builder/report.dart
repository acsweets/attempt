///一个适合使用 Builder 设计模式 的场景可以是 生成复杂的报告（Report）。
///假设你正在开发一个系统，允许用户生成不同格式的报告，例如 PDF、HTML、Excel 报告
///，每个报告包含多个可选部分，比如标题页、内容部分、图表、页脚等。
///生成报告的逻辑复杂且多样化，适合使用 Builder 模式来灵活地构建这些报告。
//
// 场景描述：复杂的报告生成系统
// 你需要生成不同格式的报告（如 PDF、HTML、Excel），每个报告的组成部分可以包括：
//
// 标题页（可选）
// 内容部分（可选，可能包含多种格式的内容）
// 图表部分（可选，支持不同的图表类型：饼图、柱状图等）
// 页脚（可选，带有日期和签名等信息）
// 各类报告的生成规则不同，某些部分可能会省略，或者某些部分的格式会有所不同，比如：
//
// PDF 报告可能要包含封面、内容、图表、页脚；
// HTML 报告可能只包含内容部分和图表；
// Excel 报告则可能只包含内容部分和表格数据。
///适用 Builder 模式的原因：
/// 组合复杂性：报告的各个部分（标题页、内容、图表、页脚等）可能有很多组合方式，使用 Builder 模式可以灵活地选择不同部分进行组合，而不是通过多个构造函数来传递参数。
/// 可扩展性：未来可能增加更多报告的格式或部分（如表格、附录等），Builder 模式可以很容易扩展，不需要修改现有代码。
/// 清晰的分步构建过程：生成报告可以是一个分步过程，每一步生成不同的部分，Builder 模式让这个过程更清晰和可维护。
/// 避免构造函数过载：如果通过构造函数传递所有的可选部分，可能会出现构造函数重载或者顺序混乱的情况，而 Builder 模式避免了这一点。
/// 抽象场景类设计：
/// Report 类：代表最终生成的报告，包含标题页、内容、图表和页脚等部分。
/// ReportBuilder 接口：定义生成每个报告部分的方法（如 addTitlePage()、addContent() 等），并且有一个 build() 方法生成最终的报告。
/// PdfReportBuilder、HtmlReportBuilder、ExcelReportBuilder：具体实现 ReportBuilder，负责生成不同格式的报告。
/// ReportDirector：负责控制构建流程，比如根据用户的选择构建不同的报告部分。
///
